"""
Domain scaling for maps with more obstacles (section 3 of the design).

Idea: keep the domain in the family [0,L]x[0,L] and grow L together with n so
that max_radius(n, L) -- and therefore the size diversity and the relative
density of the maps -- stays the same as the one already validated today at
n=95 @ L=1. L=1 comes out exact at n=95 (the reference point of the design).

Physical constants (ROBOT_RADIUS, step_size, exclusion/safety margins) have to
scale LINEARLY with L, or the problem stops being "equivalent" to today's one:
a robot that does not grow with the map becomes relatively tiny: a step that
does not grow needs ~L times more steps to cross the map.

MIN_RADIUS (0.015) does NOT scale: it is a design parameter, not a geometric
one (section 3.3 of the document). If, when validating empirically n=1000 @
L~3.25, the success rate comes out bad, check THIS first (maybe at that scale
0.015 is an obstacle too small to be relevant).
"""
import math

MAX_DENSITY = 0.35
R_REF = 0.0343  # reference max_radius: the densest map already validated, n=95 @ L=1
MIN_RADIUS = 0.015  # fixed, does not scale with L

# Base constants, defined for today's domain (L=1)
ROBOT_RADIUS_BASE = 0.02
GENERATOR_EXCLUSION_RADIUS_BASE = 0.15
START_GOAL_MARGIN_BASE = 0.02
SAFETY_MARGIN_BASE = 0.05
STEP_SIZE_BASE = 0.015
ARRIVAL_RADIUS_BASE = 0.05  # "reached the goal" tolerance in evaluate_trajectory

# ---------------------------------------------------------------------------
# Tile geometry
# ---------------------------------------------------------------------------
# Side of ONE universal tile. Unlike the old single-domain scheme, this does
# NOT grow with n: a tile is always [0, TILE_SIDE]^2 and the mosaics are built
# by tiling it (see src/pipeline/assembler.py). Every module that used to
# redefine this locally imports it from here instead.
TILE_SIDE = 1.0

# ---------------------------------------------------------------------------
# Engine limit
# ---------------------------------------------------------------------------
# MUST match `#define MAX_OBSTACULOS` in engine/HPPMDinamico3.c -- line 21 of
# that file. The C engine stores obstacles in a FIXED-SIZE array and IGNORES
# any extra ones IN SILENCE (no error, no warning), so a Python-side guard that
# is higher than the .c value would happily send a mosaic to HPPM that the
# engine would then verify on a truncated obstacle set -- reporting a bogus
# "success" for a map it never fully checked.
#
# If the compiled .c changes, change this value BY HAND: there is no way to
# read the #define from Python. The .c is never edited from here, and it is
# authoritative -- this constant follows it, not the other way round.
ENGINE_MAX_OBSTACLES = 1000  # engine/HPPMDinamico3.c:21

# ---------------------------------------------------------------------------
# CLI interface defaults
# ---------------------------------------------------------------------------
# These are NOT physical constants: they are the `default=` values offered by
# the argparse flags of the entry points, centralised here so that every script
# agrees on the same number. Changing a VALUE changes observable behaviour;
# renaming is a UI change. They are deliberately prefixed DEFAULT_ so they are
# never confused with the physical constants above.
DEFAULT_PORT_MARGIN = 0.04        # --port-margin: obstacle-free halo around each port
DEFAULT_CONFIDENCE_RADIUS = 0.04  # --confidence-radius: geometric pre-filter radius (DIFFERENT concept from DEFAULT_PORT_MARGIN, same value by coincidence)
DEFAULT_MAX_CLUSTER = 4           # --max-cluster: largest tolerated overlap cluster
DEFAULT_OVERLAP_MARGIN = 0.0      # --overlap-margin: strict criterion (see STRICT_OVERLAP_MARGIN)
DEFAULT_TILE_N_MAX = 50           # --num-obs-max / --n-max: top of the tile range generated by the dataset pipeline
DEFAULT_PORTS_PER_SIDE = 3        # --ports-per-side: P in the 4*P port-to-centre routes
DEFAULT_L = TILE_SIDE             # --L: the domain side, fixed for the tiles scheme
DEFAULT_M1 = 1.0                  # --m1 (homotopy slope)
DEFAULT_M2 = 4.0                  # --m2: see the NOTICE below, the compiled engine ignores it
DEFAULT_GUIDANCE = 1.0            # --guidance: classifier-free guidance weight
DEFAULT_SEED = 42                 # --seed: RNG seed
DEFAULT_TIMEOUT = 5.0             # --timeout: seconds per HPPM run
DEFAULT_DDIM_STEPS = 100          # --ddim-steps: number of DDIM sampling steps

# NOTICE on DEFAULT_M2 (and DEFAULT_M1): the compiled engine does NOT read
# these. `leer_archivos_configuracion` in HPPMDinamico3.c scans the m1/m2
# fields of pendientes.txt but then assigns hardcoded 1.0/4.0, so passing a
# different value has no effect on the actual path planning. The flags are kept
# because the file format and every caller still carry the two numbers, and
# because the alternative engine variant did honour them. See
# docs/universal_tiles_report.md section 4.4. Do not treat a change here as
# a behaviour change.

ROUTES = {
    "diagonal":         lambda L: ((0.0, 0.0), (L, L)),
    "diagonal_inverse": lambda L: ((0.0, L), (L, 0.0)),
    "horizontal":       lambda L: ((0.0, L / 2), (L, L / 2)),
    "vertical":         lambda L: ((L / 2, L), (L / 2, 0.0)),
}


def compute_L(n: int, r_ref: float = R_REF, max_density: float = MAX_DENSITY) -> float:
    """Side L of the square domain such that max_radius(n, L) == r_ref, that
    is, the same relative diversity as the densest run already validated
    (n=95 @ L=1). L(95) = 1.0 exactly, L(1000) ~= 3.25 (section 3.2)."""
    return r_ref * math.sqrt(n * math.pi / max_density)


def max_radius(n: int, L: float, max_density: float = MAX_DENSITY) -> float:
    return math.sqrt(max_density * (L * L) / (n * math.pi))


def compute_compatible_L(n: int, cutoff_n: int = 100, r_ref: float = R_REF,
                         max_density: float = MAX_DENSITY) -> float:
    """Like compute_L, but preserves L=1.0 (the domain of the current
    dataset/checkpoint) for n <= cutoff_n, and only starts growing the domain
    above that point. compute_L(n) on its own gives L<1 for n<95 (it shrinks
    the domain with respect to today's) -- that breaks comparability with the
    maps already used for training. cutoff_n=100 because the historical
    dataset covers n in [5,100] (see section 1 of the design);
    compute_L(100)=1.028, so the splice at cutoff_n is almost continuous (jump
    of ~3%, not a step)."""
    if n <= cutoff_n:
        return 1.0
    return compute_L(n, r_ref, max_density)


def route_points(name: str, L: float):
    """(start, goal) of one of the 4 route families, in the domain
    [0,L]x[0,L]. 'diagonal_inverse' and 'vertical' are 'diagonal'/'horizontal'
    rotated 90 degrees -- they come for free, they do not need new data to be
    trained (section 2.4 of the design)."""
    if name not in ROUTES:
        raise ValueError(f"unknown route: {name!r}. Options: {sorted(ROUTES)}")
    return ROUTES[name](L)


def scaled_constants(L: float) -> dict:
    """ROBOT_RADIUS, exclusion/safety margins and step_size scaled linearly by
    L (section 3.3)."""
    return {
        "robot_radius": ROBOT_RADIUS_BASE * L,
        "generator_exclusion_radius": GENERATOR_EXCLUSION_RADIUS_BASE * L,
        "start_goal_margin": START_GOAL_MARGIN_BASE * L,
        "safety_margin": SAFETY_MARGIN_BASE * L,
        "step_size": STEP_SIZE_BASE * L,
        "arrival_radius": ARRIVAL_RADIUS_BASE * L,
    }


# The assembled mosaic is verified with ONE HPPM route, start corner -> goal corner
# (verify_global). It is NOT the 4*P-route port->center criterion every individual
# tile passed before being placed (src.model.set_diffusion._verify_universal_candidate).
MOSAIC_VERIFICATION_SCOPE = {
    "criterion": "single_route_corner_to_corner",
    "hppm_routes_per_verification": 1,
    "tile_12_route_criterion": False,
    "note": ("The mosaic is verified ONLY with the start->goal corner-to-corner route "
             "(default start=(0,0), goal=(columns, rows)); it is NOT re-verified with the "
             "per-tile 4*P port->center criterion (12 routes at P=3). Each individual tile "
             "did pass that criterion before placement."),
}
