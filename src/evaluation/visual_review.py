"""
visual_review.py — Visual validation of generated/verified maps.

Runs from the Universal_Tiles/ project root (the package modules are imported
as src.common.* / src.dataset.*), over an output folder already generated by
`src.dataset.universal_generator` (or `src.dataset.repaired_generator`), that
is, any folder that has:
    maps.npz
    results_detail.json

Each map may live in its own domain [0,L]x[0,L] with its own route
(start/goal) -- see src/common/domain_scaling.py. This script reads
L/start/goal FOR EACH MAP from results_detail.json (that is how
repaired_generator.py and universal_generator.py save them); if a record does
not carry them (old datasets, from before domain scaling), it falls back to
L=1, start=(0,0), goal=(1,1) with a warning -- it does not do it silently.

Two modes:

1. "grid": quick contact sheet (without re-running HPPM) with N random maps of
   a given status (by default "success"). It is useful for a quick visual
   sweep: do the maps labelled as success look reasonable? are there
   obstacles stuck to the start/goal, strange shapes, obvious holes in the
   route band?

   python3 -m src.evaluation.visual_review grid \
       --dir artifacts/universal_n01-50_P3_lote1_s142 --status success -n 30
       # (--status accepts success | collision | loop_stagnation | timeout)

2. "detail": re-runs HPPM over a SINGLE given map to obtain the real
   trajectory and plot it on top of the obstacles, with the minimum clearance
   (distance closest to any obstacle along the route) annotated. Useful to
   review borderline cases by hand: successes with very small clearance
   (possible numerical boundary) or dubious collisions.

   python3 -m src.evaluation.visual_review detail \
       --dir artifacts/universal_n01-50_P3_lote1_s142 --idx 17 \
       --hppm-exe artifacts/hppm_v2

   python3 -m src.evaluation.visual_review detail \
       --dir artifacts/universal_n01-50_P3_lote1_s142 --idx 17 \
       --hppm-exe artifacts/hppm_v2 --min-clearance 0.01
       # (automatically filters the N indices of that status with clearance
       #  below the threshold, instead of asking for a single idx; see --help)
"""
import argparse
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from src.common.domain_scaling import (GENERATOR_EXCLUSION_RADIUS_BASE, ROBOT_RADIUS_BASE,
                                       scaled_constants)  # noqa: E402
from src.common.compat import normalize
from src.common.maps_io import load_maps  # noqa: E402
from src.common.domain_scaling import (DEFAULT_M1, DEFAULT_M2, DEFAULT_SEED)

STATE_COLORS = {
    "success": "#2e7d32",
    "collision": "#c62828",
    "loop_stagnation": "#ef6c00",
    "timeout": "#6a1b9a",
}

# ==========================================================================
# FROZEN campaign configuration.
# These were argparse flags; they are now module constants holding the exact
# `default=` the campaign ran with. Do not change a value here.
# ==========================================================================
COLS = 6             # --cols (grid)
IDX = None           # --idx (detail)
MAX_REVIEW = 20      # --max-review (detail)
MIN_CLEARANCE = None  # --min-clearance (detail)
STEP_SIZE = None     # --step-size (detail; None = step_size scaled to the L of each map)
TIMEOUT = 2.0        # --timeout (detail)

_FALLBACK_WARNING_GIVEN = set()  # only once per folder, not per map


# --------------------------------------------------------------------------
def load_detail_results(folder):
    path = os.path.join(folder, "results_detail.json")
    with open(path, encoding="utf-8") as f:
        detail = normalize(json.load(f))
    return {int(r["idx"]): r for r in detail}


def geometry_of(r, folder):
    """L, start, goal of one record of results_detail.json. If they are
    missing (old dataset, pre-domain-scaling), it falls back to L=1/(0,0)/(1,1)
    with ONE warning per folder, not silently."""
    if "L" not in r or "start" not in r or "meta" not in r:
        if folder not in _FALLBACK_WARNING_GIVEN:
            print(f"  WARNING [{folder}]: results_detail.json without 'L'/'start'/'meta' "
                  f"(dataset from before domain scaling) -- assuming L=1, (0,0)->(1,1).")
            _FALLBACK_WARNING_GIVEN.add(folder)
        return 1.0, (0.0, 0.0), (1.0, 1.0)
    return float(r["L"]), tuple(r["start"]), tuple(r["meta"])


def load_all(folder):
    """Returns dict idx -> {"obs": (n,4) array x,y,r,p_neto, **result}."""
    idxs, maps = load_maps(folder, columns=4)
    detail = load_detail_results(folder)
    out = {}
    for idx, obs in zip(idxs, maps):
        if idx not in detail:
            continue
        out[idx] = {"obs": obs, **detail[idx]}
    return out


# --------------------------------------------------------------------------
def draw_map(ax, obs, status=None, traj=None, title=None,
             start=(0.0, 0.0), goal=(1.0, 1.0), L=1.0, robot_radius=ROBOT_RADIUS_BASE,
             exclusion_radius=GENERATOR_EXCLUSION_RADIUS_BASE):
    """obs: array (n,4) columns x,y,r,p_neto (p_neto may be all-zero if
    repulsion was not computed; in that case everything is drawn in grey).
    The axes margin and the exclusion zones scale with L; robot_radius/
    exclusion_radius come ALREADY scaled (see
    domain_scaling.scaled_constants)."""
    margin = 0.05 * L
    ax.set_xlim(-margin, L + margin)
    ax.set_ylim(-margin, L + margin)
    ax.set_aspect("equal")
    ax.set_xticks([])
    ax.set_yticks([])

    # reference band start->goal (the real route of this map, not always diagonal)
    ax.plot([start[0], goal[0]], [start[1], goal[1]],
            "--", color="0.75", linewidth=0.8, zorder=1)

    for x, y, r, p in obs:
        if p > 0:
            color = "#1565c0"   # "positive" repulsion (one side of the route)
        elif p < 0:
            color = "#ef6c00"   # "negative" repulsion (the other side)
        else:
            color = "0.55"      # no repulsion info (p_neto not computed)
        ax.add_patch(plt.Circle((x, y), r, facecolor=color, edgecolor="none",
                                 alpha=0.55, zorder=2))
        # effective collision radius of the robot (scaled to L) in dotted line
        ax.add_patch(plt.Circle((x, y), r + robot_radius, facecolor="none",
                                 edgecolor=color, linewidth=0.4, alpha=0.5, zorder=2))

    # exclusion zones around start/goal (scaled to L)
    for p in (start, goal):
        ax.add_patch(plt.Circle(p, exclusion_radius, facecolor="none",
                                 edgecolor="0.6", linestyle=":", linewidth=0.7, zorder=1))

    ax.plot(*start, "s", color="black", markersize=4, zorder=4)
    ax.plot(*goal, "*", color="black", markersize=7, zorder=4)

    if traj is not None and len(traj):
        traj_color = STATE_COLORS.get(status, "black")
        ax.plot(traj[:, 0], traj[:, 1], "-", color=traj_color, linewidth=1.3, zorder=3)

    if title:
        edge_color = STATE_COLORS.get(status, "black")
        ax.set_title(title, fontsize=8, color=edge_color)


# --------------------------------------------------------------------------
def cmd_grid(args):
    data = load_all(args.dir)
    candidates = [idx for idx, r in data.items() if r["state"] == args.status]
    if not candidates:
        print(f"There are no maps with status='{args.status}' in {args.dir}")
        return
    rng = np.random.default_rng(args.seed)
    chosen = rng.choice(candidates, size=min(args.n, len(candidates)), replace=False)

    cols = COLS
    rows = int(np.ceil(len(chosen) / cols))
    fig, axs = plt.subplots(rows, cols, figsize=(2.1 * cols, 2.1 * rows))
    axs = np.atleast_2d(axs)

    for k, idx in enumerate(chosen):
        ax = axs[k // cols][k % cols]
        r = data[idx]
        L_i, start_i, goal_i = geometry_of(r, args.dir)
        const = scaled_constants(L_i)
        route_txt = r.get("ruta", "?")
        title = f"#{idx} n={len(r['obs'])} {route_txt[:4]} L={L_i:.1f}"
        draw_map(ax, r["obs"], status=r["state"], title=title,
                 start=start_i, goal=goal_i, L=L_i,
                 robot_radius=const["robot_radius"],
                 exclusion_radius=const["generator_exclusion_radius"])
    for k in range(len(chosen), rows * cols):
        axs[k // cols][k % cols].axis("off")

    fig.suptitle(f"{args.dir} — status='{args.status}' ({len(chosen)} of {len(candidates)})",
                 fontsize=10)
    fig.tight_layout(h_pad=1.8)
    out = args.out or os.path.join(args.dir, f"contact_sheet_{args.status}.png")
    fig.savefig(out, dpi=140)
    print(f"Saved: {out}  ({len(candidates)} '{args.status}' maps available in total)")


# --------------------------------------------------------------------------
def _rerun_hppm(obs4, hppm_exe, step_size, timeout, start, goal, robot_radius, arrival_radius, m1, m2):
    from src.dataset.verify_maps import verify_one_map
    _, res = verify_one_map((0, obs4, hppm_exe, step_size, timeout, True,
                             start, goal, robot_radius, arrival_radius, m1, m2))
    return res


def cmd_detail(args):
    data = load_all(args.dir)
    if IDX is not None:
        targets = [IDX]
    else:
        # no single idx: walk all the maps of the requested status and filter
        # by real minimum clearance (re-runs HPPM on each one, may take a while)
        targets = [idx for idx, r in data.items() if r["state"] == args.status]
        if MAX_REVIEW:
            targets = targets[:MAX_REVIEW]

    for idx in targets:
        if idx not in data:
            print(f"idx {idx} does not exist in {args.dir}")
            continue
        r = data[idx]
        obs = r["obs"]
        L_i, start_i, goal_i = geometry_of(r, args.dir)
        const = scaled_constants(L_i)
        step = STEP_SIZE if STEP_SIZE is not None else const["step_size"]
        # NOTE: the compiled engine ignores m1/m2 (it overwrites them with 1.0/4.0).
        res = _rerun_hppm(obs, args.hppm_exe, step, TIMEOUT, start_i, goal_i,
                          const["robot_radius"], const["arrival_radius"], DEFAULT_M1, DEFAULT_M2)
        traj = res.get("tray", np.zeros((0, 2)))

        # real minimum clearance along the trajectory (with the robot_radius
        # scaled to the L of THIS map, not a fixed value)
        clearance = float("inf")
        for x, y in traj:
            for ox, oy, orad, _ in obs:
                d = np.hypot(x - ox, y - oy) - (orad + const["robot_radius"])
                clearance = min(clearance, d)
        clearance_txt = f"{clearance:.4f}" if np.isfinite(clearance) else "n/a"

        if MIN_CLEARANCE is not None and (not np.isfinite(clearance) or clearance > MIN_CLEARANCE):
            continue  # not a borderline case, skip

        fig, ax = plt.subplots(figsize=(5, 5))
        title = (f"{args.dir} idx {idx} | route={r.get('ruta', '?')} | L={L_i:.2f} | "
                 f"saved='{r['state']}' recomputed='{res['state']}' | min_clearance={clearance_txt}")
        draw_map(ax, obs, status=res["state"], traj=traj, title=title,
                 start=start_i, goal=goal_i, L=L_i,
                 robot_radius=const["robot_radius"],
                 exclusion_radius=const["generator_exclusion_radius"])
        fig.tight_layout()
        out = os.path.join(args.dir, f"detail_idx{idx}.png")
        fig.savefig(out, dpi=150)
        plt.close(fig)
        print(f"idx {idx}: saved='{r['state']}'  recomputed='{res['state']}'  "
              f"min_clearance={clearance_txt}  -> {out}")
        if res["state"] != r["state"]:
            print("  *** WARNING: the saved status does not match the recomputed one ***")


# --------------------------------------------------------------------------
def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    pg = sub.add_parser("grid", help="contact sheet of N random maps (fast, without HPPM)")
    pg.add_argument("--dir", required=True)
    pg.add_argument("--status", default="success",
                    help="success | collision | loop_stagnation | timeout")
    pg.add_argument("-n", type=int, default=24)
    pg.add_argument("--seed", type=int, default=DEFAULT_SEED)
    pg.add_argument("--out", default=None)
    pg.set_defaults(func=cmd_grid)

    pd = sub.add_parser("detail", help="runs HPPM over 1+ maps to see the real trajectory")
    pd.add_argument("--dir", required=True)
    pd.add_argument("--status", default="success",
                    help="if --idx is not given, walks all the maps with this status")
    pd.add_argument("--hppm-exe", required=True)
    pd.set_defaults(func=cmd_detail)

    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
